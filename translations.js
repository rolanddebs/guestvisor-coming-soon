function setLanguage(code, updateUrl = true) {
  const lang = Object.prototype.hasOwnProperty.call(translations, code) ? code : "en";
  const pack = translations[lang];
  document.documentElement.setAttribute("lang", lang === "zh" ? "zh-Hans" : lang);
  document.documentElement.setAttribute("dir", lang === "ar" ? "rtl" : "ltr");
  document.title = pack.pageTitle;
  const langControl = document.getElementById("language");
  if (langControl) langControl.value = lang;
  document.querySelectorAll("[data-t]").forEach(el => {
    const key = el.getAttribute("data-t");
    el.textContent = pack[key] || translations.en[key] || "";
  });
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.setAttribute("content", pack.intro + " " + pack.prelaunch);
  if (updateUrl) {
    try {
      const u = new URL(window.location.href);
      if (lang === "en") u.searchParams.delete("lang");
      else u.searchParams.set("lang", lang);
      window.history.replaceState(null, "", u.pathname + u.search + u.hash);
    } catch (_) { /* local file preview: page still fully translated */ }
  }
}
const selected = new URLSearchParams(window.location.search).get("lang");
setLanguage(selected || "en", false);
document.getElementById("language").addEventListener("change", event => setLanguage(event.target.value));
